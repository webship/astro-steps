'use strict';

// Step definitions for what an Astro build produces: who made the page, the
// production build, the JavaScript a page ships, scoped styles, the 404 page,
// the sitemap and the RSS feed, and the page title.

const { Then } = require('@cucumber/cucumber');
const {
  budget, escapeRegExp, poll, fetchSiteFile, friendly,
} = require('./astro-helpers');

const GENERATOR_HINT = 'Astro writes `<meta name="generator" content="Astro vX.Y.Z">` into a page when the layout adds `Astro.generator`; a page served from another tool, a proxy error page or a `<head>` that strips the tag will not carry it.';

/**
 * Wait until the page's <meta name="generator"> content satisfies `test`
 * (or, with `notCase`, does not), then return it. Throws a friendly error
 * with the content that was found when the budget runs out.
 */
async function waitForGenerator(world, notCase, test, { message, hint = GENERATOR_HINT }) {
  const timeout = budget(world);
  try {
    await world.page.waitForFunction(
      ({ src, want }) => {
        const meta = document.querySelector('meta[name="generator"]');
        const content = meta ? meta.getAttribute('content') || '' : '';
        return Boolean(new RegExp(src, 'i').test(content)) === want;
      },
      { src: test.source, want: !notCase },
      { timeout }
    );
  } catch {
    const content = await world.page.locator('meta[name="generator"]').first().getAttribute('content').catch(() => null);
    throw friendly({
      message: `${message} ${content === null ? 'No <meta name="generator"> tag was found.' : `The generator meta tag is "${content}".`}`,
      hint,
    });
  }
}

/**
 * Assert the current page was (or was not) rendered by Astro, via its
 * generator meta tag. Both the markup-flavoured phrasing ("the Astro
 * generator meta tag") and the site-flavoured one ("generated by Astro")
 * are one step.
 *
 * Example #1: Then I should see the Astro generator meta tag
 * Example #2: Then we should not see the Astro generator meta tag
 * Example #3: And the page should be generated by Astro
 * Example #4: But the page should not be generated by Astro
 * Example #5: Then should see the Astro generator meta tag
 */
Then(/^(?:(?:I |we )*should( not)* see the Astro generator meta tag|(?:the )?page should( not)* be generated by Astro)$/, async function (notSee, notGenerated) {
  const notCase = notSee || notGenerated;
  await waitForGenerator(this, notCase, /^astro/, {
    message: notCase
      ? 'Expected the page not to be generated by Astro, but it is.'
      : 'Expected the page to be generated by Astro (a generator meta tag starting with "Astro").',
  });
});

/**
 * Assert the current page was (or was not) generated by a specific Astro
 * version. Matches from the start, so "7" matches "Astro v7.4.11" and "7.4"
 * matches it too, but "4" does not.
 *
 * Example #1: Then the page should be generated by Astro version "7"
 * Example #2: Then the page should be generated by Astro version "7.4.11"
 * Example #3: And the page should be generated by Astro version "7.4"
 * Example #4: But the page should not be generated by Astro version "4"
 * Example #5: Then page should be generated by Astro version "7.4"
 */
Then(/^(?:the )?page should( not)* be generated by Astro version "([^"]*)?"$/, async function (notCase, version) {
  await waitForGenerator(this, notCase, new RegExp(`^astro v${escapeRegExp(version)}`), {
    message: notCase
      ? `Expected the page not to be generated by Astro version "${version}", but it is.`
      : `Expected the page to be generated by Astro version "${version}".`,
    hint: 'The version is matched from its start against the "vX.Y.Z" part of the generator meta tag; check the Astro version in the site\'s package.json.',
  });
});

/**
 * Assert the page was (or was not) served by a production build. `astro dev`
 * adds the dev toolbar (`astro-dev-toolbar`), the Vite client
 * (`/@vite/client`) and `data-astro-source-file` attributes; `astro build`
 * adds none of them.
 *
 * Example #1: Then the site should be a production build
 * Example #2: And the site should be a production build
 * Example #3: But the site should not be a production build
 * Example #4: Then site should be a production build
 * Example #5: Then the site should be served as a production build
 */
Then(/^(?:the )?site should( not)* be (?:served as )?a production build$/, async function (notCase) {
  let seen;
  const ok = await poll(this, async () => {
    seen = await this.page.evaluate(() => ({
      vite: Boolean(document.querySelector('script[src*="/@vite/client"]')),
      toolbar: Boolean(document.querySelector('astro-dev-toolbar')),
      source: Boolean(document.querySelector('[data-astro-source-file]')),
    }));
    const development = seen.vite || seen.toolbar || seen.source;
    return development === Boolean(notCase);
  }, 3000);
  if (!ok) {
    throw friendly({
      message: notCase
        ? 'Expected the development server, but the page is a production build (no Vite client, dev toolbar or source attributes).'
        : `Expected a production build, but the page looks like \`astro dev\` (Vite client: ${seen.vite}, dev toolbar: ${seen.toolbar}, source attributes: ${seen.source}).`,
      hint: 'Run `astro build` and serve `dist/` with `astro preview`; the suite needs the production build, and LAUNCH_URL must point at it.',
    });
  }
});

// The scripts a page runs: not data blocks.
const DATA_SCRIPT_TYPES = /^(application\/(ld\+)?json|importmap|speculationrules|text\/template)$/i;

/**
 * The executable scripts and the islands in the HTML Astro sent.
 *
 * @param {string} html
 * @returns {{scripts: string[], islands: number}}
 */
function shippedJavaScript(html) {
  const scripts = [];
  for (const match of html.matchAll(/<script\b([^>]*)>/gi)) {
    const type = (match[1].match(/\btype\s*=\s*["']?([^"'\s>]+)/i) || [])[1];
    if (type && DATA_SCRIPT_TYPES.test(type)) continue;
    const src = (match[1].match(/\bsrc\s*=\s*["']?([^"'\s>]+)/i) || [])[1];
    scripts.push(src || 'an inline script');
  }
  return { scripts, islands: (html.match(/<astro-island\b/gi) || []).length };
}

/**
 * Assert the page does (or does not) ship JavaScript. Astro sends plain HTML
 * unless the page uses a client directive, `<ClientRouter />` or a script, so
 * a content page that ships none is as fast as static HTML. The step reads
 * the HTML that the server sent, not the DOM after the scripts ran.
 *
 * Example #1: Then the page should not ship JavaScript
 * Example #2: And the page should not ship JavaScript
 * Example #3: But the page should ship JavaScript
 * Example #4: Then page should not ship JavaScript
 * Example #5: And the page should not ship any JavaScript
 */
Then(/^(?:the )?page should( not)* ship (?:any )?JavaScript$/, async function (notCase) {
  const file = await fetchSiteFile(this, this.page.url(), 'The page could not be requested; check LAUNCH_URL.');
  const { scripts, islands } = shippedJavaScript(file.text);
  const ships = scripts.length > 0 || islands > 0;
  if (ships === !notCase) return;
  throw friendly({
    message: notCase
      ? `Expected no JavaScript on ${file.url}, but the page ships ${scripts.length} script(s)${islands ? ` and ${islands} island(s)` : ''}: ${scripts.slice(0, 3).join(', ')}.`
      : `Expected the page to ship JavaScript, but ${file.url} is plain HTML.`,
    hint: 'Astro adds JavaScript for a client directive (`client:load`, ...), `<ClientRouter />` and `<script>` tags in components; a layout that every page shares can add it to all of them.',
  });
});

/**
 * Assert the page has (or has not) scoped styles: Astro marks the elements of
 * a component that has a `<style>` with `data-astro-cid-<hash>` and writes the
 * rules against the same attribute.
 *
 * Example #1: Then the page should have scoped styles
 * Example #2: And the page should have scoped styles
 * Example #3: But the page should not have scoped styles
 * Example #4: Then page should have scoped styles
 * Example #5: And the page should have scoped styles
 */
Then(/^(?:the )?page should( not)* have scoped styles$/, async function (notCase) {
  const ok = await poll(this, async () => {
    const found = await this.page.evaluate(() => Array.from(document.querySelectorAll('*')).some((element) => element.getAttributeNames().some((name) => name.startsWith('data-astro-cid-'))));
    return found === !notCase;
  }, 3000);
  if (!ok) {
    throw friendly({
      message: notCase
        ? 'Expected no scoped styles, but elements with data-astro-cid-* attributes are on the page.'
        : 'Expected elements with data-astro-cid-* attributes (scoped styles), but there are none.',
      hint: 'Scoped styles come from a `<style>` block in an `.astro` component that the page renders (without `is:global`).',
    });
  }
});

/**
 * Assert the build has (or has not) a 404 page: `404.html` is served as HTML.
 * Astro builds it from `src/pages/404.astro`.
 *
 * Example #1: Then the 404 page should be available
 * Example #2: And the 404 page should be available
 * Example #3: But the 404 page should not be available
 * Example #4: Then 404 page should be available
 * Example #5: And the 404 page should be available
 */
Then(/^(?:the )?404 page should( not)* be available$/, async function (notCase) {
  const file = await fetchSiteFile(this, '/404.html', 'The site could not be requested; check LAUNCH_URL.');
  const built = file.status === 200 && /html/.test(file.type);
  if (built === Boolean(notCase)) {
    throw friendly({
      message: notCase
        ? 'Expected no 404 page, but /404.html is served.'
        : `Expected the 404 page to be built, but /404.html answers ${file.status} (${file.type || 'no content type'}).`,
      hint: 'Create `src/pages/404.astro`; the build then writes `dist/404.html`, which `astro preview` and most hosts answer unknown addresses with.',
    });
  }
});

/**
 * Read the addresses a sitemap lists. A sitemap index (`sitemap-index.xml`,
 * written by @astrojs/sitemap) points at the sitemaps that hold the addresses.
 *
 * @param {object} world
 * @param {string} indexPath
 * @returns {Promise<{urls: string[], problem: string|null}>}
 */
async function readSitemap(world, indexPath) {
  const hint = 'Add @astrojs/sitemap to `integrations` and set `site` in astro.config; the build writes `sitemap-index.xml` and `sitemap-0.xml`.';
  const index = await fetchSiteFile(world, indexPath, hint);
  if (index.status !== 200) return { urls: [], problem: `${index.url} answers ${index.status}` };
  const locations = (xml) => Array.from(xml.matchAll(/<loc>\s*([^<\s]+)\s*<\/loc>/g), (match) => match[1]);
  if (!/<sitemapindex\b/.test(index.text)) return { urls: locations(index.text), problem: null };
  const urls = [];
  for (const sitemap of locations(index.text)) {
    const file = await fetchSiteFile(world, new URL(sitemap).pathname, hint);
    if (file.status !== 200) return { urls, problem: `${file.url} answers ${file.status}` };
    urls.push(...locations(file.text));
  }
  return { urls, problem: null };
}

/**
 * Assert the sitemap lists (or does not list) a path of the site. The step
 * reads `sitemap-index.xml` and the sitemaps it points at, and compares the
 * path of every address, so the `site` of the build does not matter.
 *
 * Example #1: Then the sitemap should list "/about/"
 * Example #2: And the sitemap should list "/posts/first-post/"
 * Example #3: But the sitemap should not list "/404/"
 * Example #4: Then sitemap should list "/blog/"
 * Example #5: And the sitemap should not list "/posts/draft-post/"
 */
Then(/^(?:the )?sitemap should( not)* list "([^"]*)?"$/, async function (notCase, wanted) {
  const { urls, problem } = await readSitemap(this, '/sitemap-index.xml');
  if (problem) {
    throw friendly({ message: `The sitemap could not be read: ${problem}.`, hint: 'Add @astrojs/sitemap to `integrations` and set `site` in astro.config.' });
  }
  const paths = urls.map((url) => { try { return new URL(url).pathname; } catch { return url; } });
  const listed = paths.includes(wanted);
  if (listed === Boolean(notCase)) {
    throw friendly({
      message: notCase
        ? `Expected the sitemap not to list "${wanted}", but it does.`
        : `Expected the sitemap to list "${wanted}", but it lists ${paths.length} path(s): ${paths.slice(0, 8).join(', ')}${paths.length > 8 ? ', ...' : ''}.`,
      hint: 'The path is compared as written, so include the trailing slash if the site has one; pages that are filtered out of the build (drafts, `filter` option of the integration) are not listed.',
    });
  }
});

/**
 * Read an RSS feed: the channel title and the item titles.
 *
 * @param {object} world
 * @param {string} feedPath
 * @returns {Promise<{url: string, status: number, ok: boolean, channel: string, titles: string[]}>}
 */
async function readFeed(world, feedPath) {
  const file = await fetchSiteFile(world, feedPath, 'Add @astrojs/rss and an endpoint such as `src/pages/rss.xml.js`.');
  const decode = (text) => text.replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'").replace(/&amp;/g, '&').trim();
  const channelXml = (file.text.match(/<channel>([\s\S]*?)(?:<item>|<\/channel>)/) || [])[1] || '';
  const titles = Array.from(file.text.matchAll(/<item>[\s\S]*?<title>([\s\S]*?)<\/title>[\s\S]*?<\/item>/g), (match) => decode(match[1]));
  return {
    url: file.url,
    status: file.status,
    ok: file.status === 200 && /<rss\b/.test(file.text),
    channel: decode((channelXml.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || ''),
    titles,
  };
}

const FEED_HINT = 'The feed comes from an endpoint that returns `rss({ title, description, site, items })` of @astrojs/rss; every item needs a title and a link.';

/**
 * Assert an RSS feed is valid RSS 2.0: it answers 200, has a channel title
 * and at least one item. The feed is `/rss.xml` unless a path is given.
 *
 * Example #1: Then the RSS feed should be valid
 * Example #2: And the RSS feed should be valid
 * Example #3: Then the RSS feed at "/blog/rss.xml" should be valid
 * Example #4: Then RSS feed should be valid
 * Example #5: And the RSS feed at "/rss.xml" should be valid
 */
Then(/^(?:the )?RSS feed(?: at "([^"]*)")? should be valid$/, async function (feedPath) {
  const feed = await readFeed(this, feedPath || '/rss.xml');
  const problems = [];
  if (!feed.ok) problems.push(feed.status === 200 ? 'the answer is not an <rss> document' : `it answers ${feed.status}`);
  else {
    if (!feed.channel) problems.push('the channel has no title');
    if (feed.titles.length === 0) problems.push('it has no items');
  }
  if (problems.length) {
    throw friendly({ message: `The RSS feed ${feed.url} is not valid: ${problems.join('; ')}.`, hint: FEED_HINT });
  }
});

/**
 * Assert an RSS feed lists (or does not list) an item by its title. The feed
 * is `/rss.xml` unless a path is given.
 *
 * Example #1: Then the RSS feed should list "The first post"
 * Example #2: And the RSS feed should list "The second post"
 * Example #3: But the RSS feed should not list "A draft post"
 * Example #4: Then the RSS feed at "/blog/rss.xml" should list "Hello"
 * Example #5: Then RSS feed should list "The first post"
 */
Then(/^(?:the )?RSS feed(?: at "([^"]*)")? should( not)* list "([^"]*)?"$/, async function (feedPath, notCase, title) {
  const feed = await readFeed(this, feedPath || '/rss.xml');
  if (!feed.ok) {
    throw friendly({ message: `The RSS feed ${feed.url} could not be read (${feed.status === 200 ? 'not an <rss> document' : `HTTP ${feed.status}`}).`, hint: FEED_HINT });
  }
  const listed = feed.titles.includes(title);
  if (listed === Boolean(notCase)) {
    throw friendly({
      message: notCase
        ? `Expected the RSS feed not to list "${title}", but it does.`
        : `Expected the RSS feed ${feed.url} to list "${title}", but it lists: ${feed.titles.join(' | ') || 'no items'}.`,
      hint: 'The title is matched exactly against the item titles; items are built from the content collection, so drafts that the endpoint filters out are not listed.',
    });
  }
});

/**
 * Assert the document title does (or does not) end with a given suffix.
 * Useful for Astro sites that append a site name to every page title (e.g.
 * "Home | My Site").
 *
 * Example #1: Then the page title should end with "| Astro Steps Demo"
 * Example #2: Then the page title should end with "| My Site"
 * Example #3: And the page title should end with "Blog"
 * Example #4: But the page title should not end with "| Draft"
 * Example #5: Then page title should end with "Docs"
 */
Then(/^(?:the )?page title should( not)* end with "([^"]*)?"$/, async function (notCase, suffix) {
  const timeout = budget(this);
  try {
    await this.page.waitForFunction(({ s, want }) => document.title.endsWith(s) === want, { s: suffix, want: !notCase }, { timeout });
  } catch {
    const title = await this.page.title();
    throw friendly({
      message: notCase
        ? `Expected the page title "${title}" not to end with "${suffix}", but it does.`
        : `Expected the page title "${title}" to end with "${suffix}".`,
      hint: 'The suffix is matched exactly, including spaces and the separator; check the layout that sets `<title>`.',
    });
  }
});

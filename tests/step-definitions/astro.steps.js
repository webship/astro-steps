'use strict';

// astro.steps.js
//
// Custom webship-js step definitions for testing Astro (https://astro.build)
// sites: the `<meta name="generator">` tag Astro emits on every page, the
// site's navigation menu, and a health-check that crawls all navigation
// links to make sure the main pages of the site actually resolve.
//
// Loaded alongside webship-js's own step definitions in this project's
// cucumber.js:
//
//   require: [
//     'node_modules/webship-js/tests/step-definitions/**/*.js',
//     'tests/step-definitions/**/*.js',
//   ],
//
// Every assertion waits for its condition (the assertion is the wait) for
// the `minWaitTime.page` budget, and every failure is a friendly error with
// a hint instead of a raw assertion stack.

const { Then } = require('@cucumber/cucumber');
const { friendly } = require('webship-js/tests/step-definitions/webship');

/** The per-assertion wait budget: `minWaitTime.page` from cucumber.js, else 10 s. */
function budget(world) {
  return Math.max((world.minWaitTime && world.minWaitTime.page) || 0, 10000);
}

const GENERATOR_HINT = 'Astro writes `<meta name="generator" content="Astro vX.Y.Z">` into every page it renders; a page served from another tool, a proxy error page or a `<head>` that strips the tag will not carry it.';

/**
 * Wait until the page's <meta name="generator"> content satisfies `test`
 * (or, with `notCase`, does not), then return it. Throws a friendly error
 * with the content that was found when the budget runs out.
 */
async function waitForGenerator(world, notCase, test, { message, hint = GENERATOR_HINT }) {
  const timeout = budget(world);
  try {
    await world.page.waitForFunction(
      ({ src, want }) => {
        const meta = document.querySelector('meta[name="generator"]');
        const content = meta ? meta.getAttribute('content') || '' : '';
        return Boolean(new RegExp(src, 'i').test(content)) === want;
      },
      { src: test.source, want: !notCase },
      { timeout }
    );
  } catch {
    const content = await world.page.locator('meta[name="generator"]').first().getAttribute('content').catch(() => null);
    throw friendly({
      message: `${message} ${content === null ? 'No <meta name="generator"> tag was found.' : `The generator meta tag is "${content}".`}`,
      hint,
    });
  }
}

// ---------------------------------------------------------------------------
// Astro identity assertions
// ---------------------------------------------------------------------------

/**
 * Assert the current page was (or was not) rendered by Astro, via its
 * generator meta tag. Both the markup-flavoured phrasing ("the Astro
 * generator meta tag") and the site-flavoured one ("generated by Astro")
 * are one step.
 *
 * Example #1: Then I should see the Astro generator meta tag
 * Example #2: Then we should not see the Astro generator meta tag
 * Example #3: And the page should be generated by Astro
 * Example #4: But the page should not be generated by Astro
 * Example #5: Then should see the Astro generator meta tag
 *
 */
Then(/^(?:(?:I |we )*should( not)* see the Astro generator meta tag|(?:the )?page should( not)* be generated by Astro)$/, async function (notSee, notGenerated) {
  const notCase = notSee || notGenerated;
  await waitForGenerator(this, notCase, /^astro/, {
    message: notCase
      ? 'Expected the page not to be generated by Astro, but it is.'
      : 'Expected the page to be generated by Astro (a generator meta tag starting with "Astro").',
  });
});

/**
 * Assert the current page was (or was not) generated by a specific Astro
 * version. Matches by prefix, so "7" matches "Astro v7.0.7".
 *
 * Example #1: Then the page should be generated by Astro version "7"
 * Example #2: Then the page should be generated by Astro version "7.0.7"
 * Example #3: And the page should be generated by Astro version "7.0"
 * Example #4: But the page should not be generated by Astro version "4"
 * Example #5: Then page should be generated by Astro version "7.1"
 *
 */
Then(/^(?:the )?page should( not)* be generated by Astro version "([^"]*)?"$/, async function (notCase, version) {
  const escaped = version.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  await waitForGenerator(this, notCase, new RegExp(`v${escaped}`), {
    message: notCase
      ? `Expected the page not to be generated by Astro version "${version}", but it is.`
      : `Expected the page to be generated by Astro version "${version}".`,
    hint: 'The version is matched as a prefix of the "vX.Y.Z" part of the generator meta tag; check the Astro version in the site\'s package.json.',
  });
});

// ---------------------------------------------------------------------------
// Page metadata
// ---------------------------------------------------------------------------

/**
 * Assert the document title does (or does not) end with a given suffix.
 * Useful for Astro sites that append a site name to every page title (e.g.
 * "Home | My Site").
 *
 * Example #1: Then the page title should end with "| Astro Steps Demo"
 * Example #2: Then the page title should end with "| My Site"
 * Example #3: And the page title should end with "Blog"
 * Example #4: But the page title should not end with "| Draft"
 * Example #5: Then page title should end with "Docs"
 *
 */
Then(/^(?:the )?page title should( not)* end with "([^"]*)?"$/, async function (notCase, suffix) {
  const timeout = budget(this);
  try {
    await this.page.waitForFunction(({ s, want }) => document.title.endsWith(s) === want, { s: suffix, want: !notCase }, { timeout });
  } catch {
    const title = await this.page.title();
    throw friendly({
      message: notCase
        ? `Expected the page title "${title}" not to end with "${suffix}", but it does.`
        : `Expected the page title "${title}" to end with "${suffix}".`,
      hint: 'The suffix is matched exactly, including spaces and the separator; check the layout that sets `<title>`.',
    });
  }
});

// ---------------------------------------------------------------------------
// Navigation menu
// ---------------------------------------------------------------------------

/**
 * Assert that the page's <nav> element contains (or does not contain)
 * links with the given text. Optionally assert each link's href contains a
 * given substring. The table has a `text` column and an optional `path`
 * (or `href`) column; the examples below show the step line, the table
 * follows it in the feature file.
 *
 * Example #1: Then I should see a navigation menu with the following links:
 * Example #2: And we should see a navigation menu with the following links:
 * Example #3: Then should see a navigation menu with the following links:
 * Example #4: But I should not see a navigation menu with the following links:
 * Example #5: And I should see a navigation menu with the following links:
 *
 */
Then(/^(I |we )*should( not)* see a navigation menu with the following links:$/, async function (pronounCase, notCase, table) {
  const timeout = budget(this);
  for (const row of table.hashes()) {
    const text = row.text || row.Text;
    const link = this.page.locator('nav a', { hasText: text }).first();
    try {
      await link.waitFor({ state: notCase ? 'hidden' : 'visible', timeout });
    } catch {
      throw friendly({
        message: notCase
          ? `Expected no navigation link with text "${text}", but one is visible.`
          : `Expected a visible navigation link with text "${text}" within ${timeout} ms.`,
        hint: 'Links are looked up inside the page `<nav>` by their visible text; check the wording and that the menu is not collapsed on this viewport.',
      });
    }
    if (notCase) continue;

    const path = row.path || row.href || row.Path || row.Href;
    if (path) {
      let href = null;
      try {
        await this.page.waitForFunction(
          ({ t, p }) => {
            const a = Array.from(document.querySelectorAll('nav a')).find((el) => (el.textContent || '').includes(t));
            return Boolean(a) && (a.getAttribute('href') || '').includes(p);
          },
          { t: text, p: path },
          { timeout }
        );
      } catch {
        href = await link.getAttribute('href').catch(() => null);
        throw friendly({
          message: `Expected the navigation link "${text}" href to contain "${path}" but got "${href}".`,
          hint: 'The `path` column is matched as a substring of the link href; with a trailing-slash site, write "/about/" or just "/about".',
        });
      }
    }
  }
});

/**
 * Crawl every link inside the page's <nav> element and assert each one
 * resolves with a non-error HTTP status. Skips mailto:, tel:, and
 * fragment-only (#...) links, which aren't page navigations.
 *
 * Example #1: Then all navigation links should resolve successfully
 * Example #2: And all navigation links should resolve successfully
 * Example #3: But all navigation links should resolve successfully
 * Example #4: Then all the navigation links should resolve successfully
 * Example #5: And all navigation links should resolve
 *
 */
Then(/^all (?:the )?navigation links should resolve(?: successfully)?$/, async function () {
  const timeout = budget(this);
  const links = this.page.locator('nav a[href]');
  try {
    await links.first().waitFor({ state: 'attached', timeout });
  } catch {
    throw friendly({
      message: `Expected the navigation menu to contain at least one link, but none appeared within ${timeout} ms.`,
      hint: 'Links are read from the page `<nav>` element; check the page has one and that it holds `<a href>` links.',
    });
  }
  const hrefs = await links.evaluateAll((els) => els.map((el) => el.getAttribute('href')));

  const skip = /^(mailto:|tel:|javascript:|#)/i;
  const failures = [];

  for (const href of hrefs) {
    if (!href || skip.test(href)) continue;

    const url = new URL(href, this.page.url()).toString();
    let status;
    try {
      const response = await this.context.request.get(url, { timeout });
      status = response.status();
    } catch (error) {
      failures.push(`${url} -> request failed: ${error.message.split('\n')[0]}`);
      continue;
    }
    if (status >= 400) {
      failures.push(`${url} -> HTTP ${status}`);
    }
  }

  if (failures.length) {
    throw friendly({
      message: `Expected all navigation links to resolve successfully, but found:\n  ${failures.join('\n  ')}`,
      hint: 'Each href is requested with the browser context; a 404 means the route is missing from the build, a request failure usually means an external host the test machine cannot reach.',
    });
  }
});

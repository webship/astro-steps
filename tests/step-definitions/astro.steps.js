'use strict';

// astro.steps.js
//
// Custom webship-js step definitions for testing Astro (https://astro.build)
// sites: the `<meta name="generator">` tag Astro emits on every page, the
// site's navigation menu, and a health-check that crawls all navigation
// links to make sure the main pages of the site actually resolve.
//
// Loaded alongside webship-js's own step definitions in this project's
// cucumber.js:
//
//   require: [
//     'node_modules/webship-js/tests/step-definitions/**/*.js',
//     'tests/step-definitions/**/*.js',
//   ],

const { Given, When, Then } = require('@cucumber/cucumber');
const assert = require('assert');

/**
 * Reads the content attribute of the page's <meta name="generator"> tag.
 * Astro sets this to a string like "Astro v7.0.7" on every page it renders.
 *
 * @param {import('playwright').Page} page
 * @returns {Promise<string|null>}
 */
async function getGeneratorMeta(page) {
  return page.locator('meta[name="generator"]').getAttribute('content');
}

// ---------------------------------------------------------------------------
// Astro identity assertions
// ---------------------------------------------------------------------------

/**
 * Assert the current page was rendered by Astro, via its generator meta tag.
 *
 * Example #1: Then I should see the Astro generator meta tag
 * Example #2: Then we should see the Astro generator meta tag
 * Example #3: And should see the Astro generator meta tag
 *
 */
Then(/^(I |we )*should see the Astro generator meta tag$/, async function () {
  const content = await getGeneratorMeta(this.page);
  assert.ok(content, 'Expected a <meta name="generator"> tag to be present, but none was found.');
  assert.ok(
    content.toLowerCase().startsWith('astro'),
    `Expected the generator meta tag to start with "Astro" but got "${content}".`
  );
});

/**
 * Assert the current page was generated by Astro (alias, reads naturally
 * in feature files that describe the site rather than the markup).
 *
 * Example #1: Then the page should be generated by Astro
 * Example #2: And the page should be generated by Astro
 * Example #3: But the page should be generated by Astro
 *
 */
Then(/^the page should be generated by Astro$/, async function () {
  const content = await getGeneratorMeta(this.page);
  assert.ok(content, 'Expected a <meta name="generator"> tag to be present, but none was found.');
  assert.ok(
    content.toLowerCase().startsWith('astro'),
    `Expected the page to be generated by Astro but the generator meta tag was "${content}".`
  );
});

/**
 * Assert the current page was generated by a specific Astro version.
 * Matches by prefix, so "7" matches "Astro v7.0.7".
 *
 * Example #1: Then the page should be generated by Astro version "7"
 * Example #2: Then the page should be generated by Astro version "7.0.7"
 * Example #3: And the page should be generated by Astro version "7.0"
 *
 */
Then('the page should be generated by Astro version {string}', async function (version) {
  const content = await getGeneratorMeta(this.page);
  assert.ok(content, 'Expected a <meta name="generator"> tag to be present, but none was found.');
  assert.ok(
    content.includes(`Astro v${version}`) || content.includes(`v${version}`),
    `Expected generator meta tag to reference Astro version "${version}" but got "${content}".`
  );
});

// ---------------------------------------------------------------------------
// Page metadata
// ---------------------------------------------------------------------------

/**
 * Assert the document title ends with a given suffix. Useful for Astro
 * sites that append a site name to every page title (e.g. "Home | My Site").
 *
 * Example #1: Then the page title should end with "| Astro Steps Demo"
 * Example #2: Then the page title should end with "| My Site"
 * Example #3: And the page title should end with "Blog"
 *
 */
Then('the page title should end with {string}', async function (suffix) {
  const title = await this.page.title();
  assert.ok(
    title.endsWith(suffix),
    `Expected page title "${title}" to end with "${suffix}".`
  );
});

// ---------------------------------------------------------------------------
// Navigation menu
// ---------------------------------------------------------------------------

/**
 * Assert that the page's <nav> element contains links with the given text.
 * Optionally assert each link's href contains a given substring.
 *
 * Example #1: Then I should see a navigation menu with the following links:
 *   | text  | path   |
 *   | Home  | /      |
 *   | About | /about |
 * Example #2: And I should see a navigation menu with the following links:
 *   | text    | path     |
 *   | Blog    | /blog    |
 *   | Contact | /contact |
 * Example #3: Then I should see a navigation menu with the following links:
 *   | text |
 *   | Home |
 *
 */
Then('I should see a navigation menu with the following links:', async function (table) {
  const rows = table.hashes();
  for (const row of rows) {
    const text = row.text || row.Text;
    const link = this.page.locator('nav a', { hasText: text }).first();
    await assert.doesNotReject(
      () => link.waitFor({ state: 'visible', timeout: 5000 }),
      `Expected to find a visible navigation link with text "${text}".`
    );

    const path = row.path || row.href || row.Path || row.Href;
    if (path) {
      const href = await link.getAttribute('href');
      assert.ok(
        href && href.includes(path),
        `Expected navigation link "${text}" href to contain "${path}" but got "${href}".`
      );
    }
  }
});

/**
 * Crawl every link inside the page's <nav> element and assert each one
 * resolves with a non-error HTTP status. Skips mailto:, tel:, and
 * fragment-only (#...) links, which aren't page navigations.
 *
 * Example #1: Then all navigation links should resolve successfully
 * Example #2: And all navigation links should resolve successfully
 * Example #3: But all navigation links should resolve successfully
 *
 */
Then(/^all navigation links should resolve successfully$/, async function () {
  const hrefs = await this.page.locator('nav a[href]').evaluateAll((links) =>
    links.map((el) => el.getAttribute('href'))
  );

  assert.ok(hrefs.length > 0, 'Expected the navigation menu to contain at least one link.');

  const skip = /^(mailto:|tel:|javascript:|#)/i;
  const failures = [];

  for (const href of hrefs) {
    if (!href || skip.test(href)) continue;

    const url = new URL(href, this.page.url()).toString();
    let status;
    try {
      const response = await this.context.request.get(url);
      status = response.status();
    } catch (error) {
      failures.push(`${url} -> request failed: ${error.message}`);
      continue;
    }
    if (status >= 400) {
      failures.push(`${url} -> HTTP ${status}`);
    }
  }

  assert.strictEqual(
    failures.length,
    0,
    `Expected all navigation links to resolve successfully, but found:\n${failures.join('\n')}`
  );
});
